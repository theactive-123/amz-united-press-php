<h2 id="steps">How to write a memoir in 8 steps</h2>

<h3 id="step-1">1. Find your focus and your question</h3>
<p>Ask yourself: what happened that changed me, and what did I learn? A strong memoir usually centers on one transformation: leaving a career, surviving an illness, raising a child with special needs, rebuilding after loss, or building a business from nothing. Try to sum it up in one sentence, for example: <em>“How losing my business taught me what success actually means.”</em> That sentence becomes your filter for every memory.</p>

<h3 id="step-2">2. Know who you’re writing for</h3>
<p>Writing for your grandchildren is different from writing for strangers in a bookshop. A family memoir can include more names, places and context. A memoir for a wider audience needs a story that matters to people who have never met you, so every chapter has to earn its place.</p>

<h3 id="step-3">3. Gather your memories</h3>
<p>Before outlining, collect raw material. Make a timeline of the period you’re writing about, then go through photos, letters, journals, emails, social media posts and old documents. Talk to people who were there; they’ll remember details you’ve forgotten. Jot down every scene that comes to mind, without judging yet.</p>
<div class="bp-tip"><p><strong>Tip:</strong> record yourself telling the stories out loud. Many people speak more naturally than they write, and a recording captures your real voice, the voice your memoir should sound like.</p></div>

<h3 id="step-4">4. Choose a structure</h3>
<p>You don’t have to start at the beginning. Common memoir structures include:</p>
<ul>
  <li><strong>Chronological:</strong> simple and clear, best for stories with a strong forward momentum.</li>
  <li><strong>Frame or flashback:</strong> open at a dramatic moment, then go back to show how you got there.</li>
  <li><strong>Braided:</strong> two timelines (for example, then and now) alternate and meet at the end.</li>
  <li><strong>Thematic:</strong> each chapter explores one theme or lesson, useful for reflective or advice-led memoirs.</li>
</ul>
<p>Whatever you choose, the story needs a clear beginning, a middle where things get harder, and an ending where something has changed.</p>

<h3 id="step-5">5. Outline your chapters</h3>
<p>Pick the 20 to 40 scenes that best show your transformation and arrange them in your chosen structure. For each chapter, note what happens, what you felt then, and what you understand now. That last part, reflection, is what turns a list of events into a memoir.</p>

<h3 id="step-6">6. Write scenes, not summaries</h3>
<figure class="bp-fig"><img src="/assets/img/lp/writing.webp" alt="A writer drafting a memoir by hand at a desk with notes and an outline" width="1254" height="1254" loading="lazy" decoding="async"><figcaption>Write the draft fast and imperfectly; you can only edit pages that exist.</figcaption></figure>
<p>“My father was strict” is a summary. A scene shows him checking your homework at the kitchen table, the clock ticking, the red pen. Use the senses, dialogue (as close as you can remember it) and specific details to put readers in the room. Then step back and reflect: what did that moment mean, then and now?</p>
<ul>
  <li><strong>Write the first draft fast.</strong> Don’t edit as you go; aim to finish.</li>
  <li><strong>Set a routine:</strong> 500 words a day adds up to a 60,000-word draft in about four months.</li>
  <li><strong>Be honest about yourself,</strong> including your mistakes. Readers trust narrators who don’t make themselves the hero of every scene.</li>
</ul>

<h3 id="step-7">7. Write about real people carefully</h3>
<p>Memoirs are full of real people, and that brings responsibility. These are general principles, not legal advice:</p>
<ul>
  <li><strong>Tell the truth as you experienced it,</strong> and keep facts separate from your opinions and feelings.</li>
  <li><strong>Change names and identifying details</strong> of private individuals when the story doesn’t need them, and note it in an author’s note.</li>
  <li><strong>Think about privacy,</strong> not just accuracy. Revealing someone’s private information can hurt them even if it’s true.</li>
  <li><strong>Talk to the people involved</strong> where you can. Some will be glad to be included.</li>
  <li><strong>Get legal advice</strong> from a publishing or media lawyer for anything that could damage someone’s reputation. The law varies by country.</li>
</ul>

<h3 id="step-8">8. Revise and edit</h3>
<p>Put the finished draft away for a few weeks, then read it as a stranger would. Cut scenes that don’t serve your central question, tighten the opening, and make sure the ending lands. Then get outside help: beta readers for reactions, a <a href="/services/book-editing-services">professional editor</a> for structure and prose, and a proofreader before publishing. Memoirists are almost always too close to their story to edit it alone.</p>

