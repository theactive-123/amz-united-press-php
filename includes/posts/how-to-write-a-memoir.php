<h2 id="prompts">12 memoir prompts to get you writing</h2>
<p>Stuck on the blank page? Pick one prompt, set a timer for 20 minutes and write without stopping. Many of these will turn into scenes in your book.</p>
<ol class="bp-ol">
  <li>The moment you realized life would never be the same.</li>
  <li>A room from your childhood, described so a stranger could walk through it.</li>
  <li>The hardest conversation you ever had, and what you wish you’d said.</li>
  <li>A decision you almost didn’t make.</li>
  <li>The person who believed in you before you believed in yourself.</li>
  <li>A smell, song or object that takes you straight back to that time.</li>
  <li>The day you failed, and what happened the next morning.</li>
  <li>Something you’ve never told anyone, and why you kept it quiet.</li>
  <li>A rule your family lived by, and when you first broke it.</li>
  <li>The first time you felt truly proud of yourself.</li>
  <li>What you would tell your younger self at the start of this story.</li>
  <li>Where you are now, and what you finally understand.</li>
</ol>
<p>Don’t worry about order or quality at this stage. The aim is to get memories onto the page, so you can see which ones belong in the book and which ones were only part of the journey.</p>

<h2 id="mistakes">Common memoir mistakes</h2>
<ul class="bp-flags">
  <li><strong>Trying to tell your whole life.</strong> Choose one story and go deep.</li>
  <li><strong>Summarizing instead of showing.</strong> Readers need scenes they can step into.</li>
  <li><strong>No reflection.</strong> Events alone aren’t a memoir; meaning is.</li>
  <li><strong>Settling scores.</strong> Readers notice when a memoir is a weapon, and they stop trusting the narrator.</li>
  <li><strong>Editing while drafting.</strong> Finish first; perfectionism stops more memoirs than anything else.</li>
  <li><strong>Publishing without an edit.</strong> A personal story deserves a professional finish.</li>
</ul>

