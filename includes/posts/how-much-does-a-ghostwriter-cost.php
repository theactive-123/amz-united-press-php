<h2 id="questions">10 questions to ask before you hire</h2>
<p>A short call answers most of what matters. Ask every ghostwriter or agency you’re considering:</p>
<ol class="bp-ol">
  <li>Can I see samples in my genre, or speak to a past client?</li>
  <li>How will you capture my voice: interviews, recordings, my own writing?</li>
  <li>What exactly does the quote include, and what costs extra?</li>
  <li>Is the price fixed, and what would change it?</li>
  <li>How is payment split across milestones?</li>
  <li>How many revision rounds are included per chapter?</li>
  <li>Who will actually write the book, and will that person change during the project?</li>
  <li>Will I own the copyright, and is that written into the contract?</li>
  <li>Do you use AI to write drafts, and if so, how?</li>
  <li>What happens if I want to stop partway through?</li>
</ol>
<p>Clear, specific answers are a good sign. Vague ones about ownership, revisions or who does the writing are worth more weight than the price.</p>

<h2 id="contract">Contract terms that protect you</h2>
<p>Price matters, but the contract decides who owns the result. Make sure yours covers:</p>
<ol class="bp-ol">
  <li><strong>Copyright assignment.</strong> In the US, a commissioned book usually isn’t automatically a “work made for hire” (see the <a href="https://www.copyright.gov/circs/circ30.pdf" target="_blank" rel="noopener">US Copyright Office guide to works made for hire</a>), so the contract should assign the copyright to you in writing, effective when you pay.</li>
  <li><strong>Credit.</strong> State whether the writer stays anonymous or gets an “as told to” or “with” credit. Most ghostwriting is uncredited.</li>
  <li><strong>Royalties.</strong> Confirm the fee is the writer’s full payment and that every royalty is yours, unless you’ve deliberately agreed a share.</li>
  <li><strong>Confidentiality.</strong> A signed NDA before you share your story or business details.</li>
  <li><strong>Originality.</strong> A promise that the text is original, not copied, recycled or generated wholesale by AI.</li>
  <li><strong>Milestones and revisions.</strong> What you pay at each stage, what you approve, and how many revision rounds are included.</li>
  <li><strong>Files and termination.</strong> You receive all drafts and files, and you keep the work completed so far if the project ends early.</li>
</ol>

