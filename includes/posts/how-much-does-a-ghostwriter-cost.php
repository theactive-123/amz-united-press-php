<h3 id="length">1. Length</h3>
<p>Word count is the starting point of every quote. A 20,000-word lead-magnet ebook and a 90,000-word novel are completely different projects. Typical lengths: short business ebooks 15,000–30,000 words, most nonfiction and memoirs 40,000–70,000, novels 70,000–100,000.</p>

<h3 id="research">2. Research and source material</h3>
<p>A book built from your existing blog posts, talks or a detailed outline costs less than one that needs primary research, fact-checking or historical accuracy. Biographies and technical books cost more for this reason.</p>

<h3 id="interviews">3. Interviews</h3>
<p>Memoirs and business books are written from conversations with you, and sometimes with family members, colleagues or clients. More interviews mean a richer book and a higher fee. Our <a href="/services/memoir-writing-services">memoir writing service</a>, for example, is built around a structured interview plan.</p>

<h3 id="genre">4. Genre and voice</h3>
<p>Fiction needs plot, structure and character work; nonfiction needs clear argument and evidence. Neither is “cheaper” in itself, but matching an experienced writer to your genre is worth paying for, because rewriting a book in the wrong voice costs more than getting it right.</p>

<h3 id="turnaround">5. Turnaround</h3>
<p>Most books take two to six months. Need it in six weeks for a launch or a conference? Expect a rush premium, because the writer has to clear other work.</p>

