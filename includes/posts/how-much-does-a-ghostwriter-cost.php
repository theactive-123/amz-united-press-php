<h2 id="pricing-models">How ghostwriters charge</h2>
<p>You’ll usually see one of four pricing models. Knowing which one you’re being offered makes quotes easier to compare.</p>

<h3 id="per-project">Flat project fee</h3>
<p>The most common model for books. You agree a total for a defined scope (word count, number of interviews, rounds of revision) and pay in milestones, for example a deposit, payments as chapters are approved, and a final payment on delivery. It’s the easiest model to budget for, and the one we recommend asking for.</p>

<h3 id="per-word">Per word</h3>
<p>Common for shorter projects and with freelancers. It’s transparent, but the final bill depends on the final length, and books often run longer than planned. If you accept a per-word rate, agree a word-count ceiling.</p>

<h3 id="per-hour">Per hour</h3>
<p>Hourly rates (often $35 to $200+) are more typical for editing, rewriting a messy draft or consulting. For a full book, hourly billing makes the total hard to predict.</p>

<h3 id="royalty-share">Lower fee plus royalties</h3>
<p>Some established ghostwriters take a reduced upfront fee in exchange for a share of sales. It can lower your initial cost, but it means sharing income from your book for years. Only agree to it deliberately, with the percentage, the formats and the duration written into the contract.</p>

<h2 id="cost-factors">5 things that change the price</h2>
